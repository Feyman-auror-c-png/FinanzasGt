export function useLocale() {
    const l = computed(() => messages[locale.value]);
    const toggleLocale = () => {
        locale.value = locale.value === 'es' ? 'en' : 'es';
        localStorage.setItem('locale', locale.value);
    };
    return { locale, l, toggleLocale };
}
